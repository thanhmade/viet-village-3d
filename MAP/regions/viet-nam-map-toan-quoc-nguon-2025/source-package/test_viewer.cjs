const {chromium}=require(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES+'/playwright');
const fs=require('fs'),path=require('path'),{pathToFileURL}=require('url');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 const errors=[],network=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(!r.url().startsWith('file:'))network.push(r.url())});
 await page.goto(pathToFileURL(path.join(__dirname,'04_Xem_Ban_Do.html')).href);
 await page.waitForTimeout(300);
 const checks=[];const check=(name,ok)=>{checks.push({name,ok});if(!ok)throw Error(name)};
 check('34 exact province paths',await page.locator('.province-hit').count()===34);
 check('14 anchored site marks',await page.locator('.site-mark').count()===14);
 const coords=await page.evaluate(()=>window.atlasInspection.data.sites.map(s=>s.page_xy));
 await page.screenshot({path:path.join(__dirname,'viewer-desktop.png')});
 await page.locator('#siteSearch').fill('hoi an');
 check('accent-insensitive site search',await page.locator('#siteList .result').count()===1);
 await page.locator('[data-site="hoi_an"]').click();
 check('site selection',await page.locator('#detail h2').textContent()==='Hội An');
 await page.locator('#siteSearch').fill('');
 await page.locator('[data-filter="planned"]').click();
 check('planned filter',await page.locator('#siteList .result').count()===4);
 await page.locator('[data-filter="all"]').click();
 await page.locator('#provincesTab').click();
 await page.locator('#provinceSearch').fill('ha noi');
 check('province search',await page.locator('#provinceList .result').count()===1);
 await page.locator('#provinceList .result').click();
 check('province exact selected shape',await page.locator('.province-hit.selected').count()===1);
 check('province heading',await page.locator('#detail h2').textContent()==='Hà Nội');
 await page.locator('#adminToggle').check();
 check('administrative layer',await page.locator('#adminArt').isVisible());
 await page.locator('#pointsToggle').uncheck();
 check('points toggle',!(await page.locator('#pointLayer').isVisible()));
 await page.locator('#pointsToggle').check();
 await page.locator('#fit').click();
 const v1=await page.evaluate(()=>window.atlasInspection.getView());await page.locator('#zoomIn').click();
 const v2=await page.evaluate(()=>window.atlasInspection.getView());check('zoom in',v2[2]<v1[2]);
 await page.locator('#zoomOut').click();
 await page.locator('#fit').click();
 await page.locator('.site-mark[data-id="hue"]').click();
 check('map point clickable',await page.locator('#detail h2').textContent()==='Huế');
 await page.locator('#fit').click();
 const before=await page.evaluate(()=>window.atlasInspection.getView());const box=await page.locator('#map').boundingBox();
 await page.mouse.move(box.x+box.width*.8,box.y+box.height*.7);await page.mouse.down();await page.mouse.move(box.x+box.width*.8+70,box.y+box.height*.7+40,{steps:4});await page.mouse.up();
 const after=await page.evaluate(()=>window.atlasInspection.getView());check('drag pans',before[0]!==after[0]);
 check('anchors unchanged',JSON.stringify(coords)===JSON.stringify(await page.evaluate(()=>window.atlasInspection.data.sites.map(s=>s.page_xy))));
 await page.setViewportSize({width:390,height:844});await page.locator('#fit').click();await page.waitForTimeout(300);
 check('mobile no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:path.join(__dirname,'viewer-mobile.png'),fullPage:true});
 check('no JS errors',errors.length===0);check('offline no network requests',network.length===0);
 fs.writeFileSync(path.join(__dirname,'viewer-validation.json'),JSON.stringify({checks,errors,network},null,2));
 console.log(JSON.stringify({checks,errors,network}));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
